#!/usr/bin/env python3
"""
Build a two-file bundle for EDA Playground.

EDA Playground gives you a "Design" pane and a "Testbench" pane.  This script
concatenates the project into:

    sim/eda_playground/design.sv      -> put in the Design pane
    sim/eda_playground/testbench.sv   -> put in the Testbench pane

The testbench file is self-contained (the .svh includes are expanded), so it
does not need an include path.  The UVM library is selected with the
"UVM / OVM" drop-down on EDA Playground.

Usage:
    python3 scripts/make_eda_bundle.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TB = ROOT / "tb"
RTL = ROOT / "rtl"
OUT = ROOT / "sim" / "eda_playground"

RTL_FILES = [
    "sha256_functions.v",
    "sha256_round.v",
    "sha256_schedule.v",
    "sha256_core.v",
]

# Order matters: each file may use classes declared earlier.
SVH_FILES = [
    "sha256_txn.svh",
    "sha256_seq_item.svh",
    "sha256_sequences.svh",
    "sha256_driver.svh",
    "sha256_monitor.svh",
    "sha256_scoreboard.svh",
    "sha256_coverage.svh",
    "sha256_agent.svh",
    "sha256_env.svh",
    "sha256_tests.svh",
]


def read(path: Path) -> str:
    return path.read_text()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    design = [
        "// =====================================================================",
        "// SHA-256 RTL -- EDA Playground Design pane",
        "// Generated by scripts/make_eda_bundle.py",
        "// =====================================================================",
        "",
    ]
    for name in RTL_FILES:
        design.append(f"// ---- {name} " + "-" * (66 - len(name)))
        design.append(read(RTL / name).rstrip())
        design.append("")
    (OUT / "design.sv").write_text("\n".join(design))

    tb = [
        "// =====================================================================",
        "// SHA-256 UVM testbench -- EDA Playground Testbench pane",
        "// Generated by scripts/make_eda_bundle.py",
        "//",
        "// Settings:",
        "//   Testbench + Design : SystemVerilog/Verilog",
        "//   UVM / OVM          : UVM 1.2  (or UVM IEEE 1800.2-2017)",
        "//   Tools & Simulators : Siemens Questa / Aldec Riviera Pro",
        "//   Top module         : tb_top",
        "//   Run options        : +UVM_TESTNAME=sha256_kat_test",
        "// =====================================================================",
        "",
        "`timescale 1ns/1ps",
        "",
        "`include \"uvm_macros.svh\"",
        "import uvm_pkg::*;",
        "",
        "// =====================================================================",
        "// Interface",
        "// =====================================================================",
        read(TB / "sha256_if.sv").rstrip(),
        "",
        "// =====================================================================",
        "// Golden model + padding helpers",
        "// =====================================================================",
        read(TB / "sha256_model_pkg.sv").rstrip(),
        "",
        "// =====================================================================",
        "// UVM verification package (includes expanded below)",
        "// =====================================================================",
        "package sha256_uvm_pkg;",
        "",
        "    import uvm_pkg::*;",
        "    import sha256_model_pkg::*;",
        "",
    ]
    for name in SVH_FILES:
        tb.append(f"    // ---- {name} " + "-" * (60 - len(name)))
        content = read(TB / name).rstrip()
        tb.append("\n".join("    " + line if line.strip() else ""
                            for line in content.splitlines()))
        tb.append("")

    tb += [
        "endpackage",
        "",
        "// =====================================================================",
        "// Assertions",
        "// =====================================================================",
        read(TB / "sha256_sva.sv").rstrip(),
        "",
        "// =====================================================================",
        "// Top level",
        "// =====================================================================",
        read(TB / "tb_top.sv").rstrip(),
        "",
    ]
    (OUT / "testbench.sv").write_text("\n".join(tb))

    print(f"wrote {OUT / 'design.sv'}")
    print(f"wrote {OUT / 'testbench.sv'}")


if __name__ == "__main__":
    main()
